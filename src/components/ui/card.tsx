import * as React from "react";

import { cn } from "@/lib/utils";

/**
 * Card — rounded-2xl, red-tinted elevated surface with a soft glow.
 * The default card carries a subtle top-left crimson wash (`bg-card-glow`).
 */
const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { glow?: boolean }
>(({ className, glow = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border border-border bg-card bg-card-glow text-card-foreground shadow-card",
      glow && "shadow-glow-red",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

